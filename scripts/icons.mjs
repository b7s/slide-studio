#!/usr/bin/env node
/**
 * scripts/icons.mjs
 *
 * Generates `resources/js/editor/icons.config.js` from the `lucide-react`
 * package installed under `node_modules/`. The exported `ICON_CATALOG` is the
 * SINGLE source of truth for icons written into slide HTML by the editor
 * engine — it must match the lucide-react version bundled in package.json so
 * saved slides keep rendering identically across builds.
 *
 * Usage:
 *   npm run icons      # regenerate the catalog from node_modules/lucide-react
 *   npm run icons:check  # verify on-disk catalog matches the package version
 *
 * To add or change an icon:
 *   1. Update the `ICONS` whitelist below (and add to `package.json`
 *      lucide-react dependency if the name isn't already shipped).
 *   2. Run `npm run icons` to regenerate `icons.config.js`.
 *   3. Commit both together.
 *
 * NEVER hand-edit paths inside icons.config.js — they are derived. To update,
 * bump `lucide-react`, run `npm run icons`, and review the diff.
 */
import { readFileSync, writeFileSync, readdirSync, existsSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join, resolve } from "node:path";

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(__dirname, "..");

const LUCIDE_ICONS_DIR = join(ROOT, "node_modules", "lucide-react", "dist", "esm", "icons");
const PACKAGE_JSON = join(ROOT, "node_modules", "lucide-react", "package.json");
const OUT_PATH = join(ROOT, "resources", "js", "editor", "icons.config.js");

// Hand-picked whitelist of icons that show up in the slide editor's icon
// palette. Icon names here MUST exist in node_modules/lucide-react/dist/esm/icons.
// The path data inside the generated catalog is sourced from that directory;
// this script is the ONLY place to edit when adding/removing icons.
const ICONS = [
  "chevron-up",
  "chevron-down",
  "chevron-left",
  "chevron-right",
  "chevrons-up",
  "chevrons-down",
  "arrow-up",
  "arrow-down",
  "arrow-left",
  "arrow-right",
  "plus",
  "minus",
  "x",
  "check",
  "heart",
  "star",
  "circle",
  "zap",
];

const UNIQUE_ICONS = [...new Set(ICONS)];

function fail(msg) {
  console.error(`scripts/icons: ${msg}`);
  process.exit(1);
}

if (!existsSync(LUCIDE_ICONS_DIR)) {
  fail(`lucide-react icons directory not found: ${LUCIDE_ICONS_DIR}. Run \`npm install\` first.`);
}

const lucidePkg = JSON.parse(readFileSync(PACKAGE_JSON, "utf8"));
const lucideVersion = lucidePkg.version;

const available = new Set(readdirSync(LUCIDE_ICONS_DIR));
const missing = UNIQUE_ICONS.filter((name) => !available.has(`${name}.mjs`));
if (missing.length > 0) {
  fail(
    `lucide-react does not ship the following icons: ${missing.join(", ")}. ` +
      "Either remove them from the script's ICONS whitelist or upgrade lucide-react."
  );
}

/**
 * Parse `node_modules/lucide-react/dist/esm/icons/<name>.mjs` and extract the
 * `__iconNode` array. The file uses a specific format:
 *   const __iconNode = [["path", { d: "...", key: "..." }], ["path", { ... }]];
 * or for multi-path icons, the same thing split over multiple lines:
 *   const __iconNode = [
 *     ["path", { d: "...", key: "..." }],
 *     ["path", { d: "...", key: "..." }],
 *   ];
 * Each entry is `[tag, attrs]` — we keep only the attrs that matter for
 * rendering (currently `d`), and emit the catalog with `{ tag, attrs }`.
 */
function parseIconNode(name) {
  const file = readFileSync(join(LUCIDE_ICONS_DIR, `${name}.mjs`), "utf8");

  // Match the variable assignment (works for single-line + multi-line forms).
  const re = /const __iconNode = (\[[\s\S]*?\]);/;
  const match = file.match(re);
  if (!match) {
    fail(`Could not locate __iconNode in ${name}.mjs — lucide file format changed?`);
  }

  // The body is a JS array literal — feed it to `eval` in a strict-ish sandbox
  // just for parsing. There's no untrusted input here; this file ships in
  // node_modules and is opaque to the rest of the project.
  let parsed;
  try {
    parsed = eval(`(${match[1]})`); // eslint-disable-line no-eval
  } catch (e) {
    fail(`Failed to parse __iconNode in ${name}.mjs: ${e.message}`);
  }

  if (!Array.isArray(parsed)) {
    fail(`__iconNode in ${name}.mjs is not an array.`);
  }

  return parsed.map((entry) => {
    if (!Array.isArray(entry) || entry.length !== 2) {
      fail(`Unexpected entry shape in ${name}.mjs: ${JSON.stringify(entry)}`);
    }
    const [tag, attrs] = entry;
    return { tag, attrs };
  });
}

const catalog = UNIQUE_ICONS.map((name) => ({
  name,
  entries: parseIconNode(name),
})).sort((a, b) => a.name.localeCompare(b.name));

const header = `// AUTO-GENERATED — DO NOT EDIT.
// Regenerated by \`npm run icons\` (scripts/icons.mjs) from node_modules/lucide-react.
// Source lucide-react version: ${lucideVersion}
// If you need to add, remove, or change an icon, update the ICONS
// whitelist in scripts/icons.mjs + (optionally) bump "lucide-react" in package.json,
// then run the script and commit both the catalog file and (if you bumped) package.json.
//
// At runtime every entry in ICON_CATALOG becomes an inline SVG with data-g4-icon=1
// inside the slide DOM; the engine reads back the data-icon-name so the catalog
// is the persistence contract for these decorations.

export const ICON_CATALOG_VERSION = ${JSON.stringify(lucideVersion)};
`;

const lines = [];
lines.push(header);
lines.push("export const ICON_CATALOG = {");
for (const entry of catalog) {
  lines.push(`  ${JSON.stringify(entry.name)}: {`);
  lines.push(`    tag: ${JSON.stringify(entry.entries.length === 1 ? entry.entries[0].tag : "multi")},`);
  if (entry.entries.length === 1) {
    lines.push(`    attrs: ${JSON.stringify(entry.entries[0].attrs)},`);
  } else {
    lines.push(`    entries: [`);
    for (const sub of entry.entries) {
      lines.push(`      { tag: ${JSON.stringify(sub.tag)}, attrs: ${JSON.stringify(sub.attrs)} },`);
    }
    lines.push(`    ],`);
  }
  lines.push(`  },`);
}
lines.push("};");
lines.push("");

const expectedOutput = lines.join("\n");
const checkOnly = process.argv.includes("--check");

if (!checkOnly) {
  writeFileSync(OUT_PATH, expectedOutput);
  console.log(`scripts/icons: wrote ${catalog.length} icon entries (lucide-react ${lucideVersion}) -> resources/js/editor/icons.config.js`);
  process.exit(0);
}

// --check: do NOT touch the file, just compare the regenerated output to what's
// already on disk. Used by `npm run icons:check` so CI can detect drift.
if (existsSync(OUT_PATH)) {
  const onDisk = readFileSync(OUT_PATH, "utf8");
  if (onDisk === expectedOutput) {
    console.log(`scripts/icons: --check OK (lucide-react ${lucideVersion}, ${catalog.length} entries).`);
    process.exit(0);
  }
}

console.error(
  "scripts/icons: --check FAILED. resources/js/editor/icons.config.js is out of date with lucide-react.\n" +
    "  Run `npm run icons` (or `npm run icons -- --write` if you want to be explicit) to regenerate, then commit both the catalog file and any package.json bump."
);
process.exit(1);
