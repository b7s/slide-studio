import {useEffect, useMemo, useRef, useState} from "react";
import {Check, Search, Type} from "lucide-react";
import {Popover, PopoverContent, PopoverTrigger} from "../Components/ui/popover";
import {FONT_CATALOG, FONT_CATEGORIES} from "./fonts.config";
import {__} from "../lib/i18n";
import {cn} from "../Components/lib/utils";

/**
 * Extract the primary family name from a CSS `font-family` value. Handles
 * quoted names ("Inter"), bare names (Inter), and full stacks
 * ("Inter",system-ui,...). Returns the unquoted first identifier.
 */
function primaryFamily(value) {
    if (!value) return "";
    const first = value.split(",")[0] ?? "";
    return first.trim().replace(/^["']|["']$/g, "");
}

/**
 * FontSelector — Popover-based font picker with live previews.
 *
 * - `value`   is the current CSS `font-family` value written to the inline
 *             style (may be a bare name or a full stack).
 * - `onChange`is called with the FULL stack of the chosen font (better
 *             cross-platform fallbacks than a bare name). Pass "" to clear.
 *
 * Fonts are sourced from `./fonts.config.js` (auto-generated by
 * `scripts/fonts.mjs`). Categories are localized via the `messages.fonts.*`
 * keys.
 */
export function FontSelector({value, onChange, disabled = false}) {
    const [open, setOpen] = useState(false);
    const [query, setQuery] = useState("");
    const searchRef = useRef(null);

    const selectedFamily = primaryFamily(value);

    // Focus + clear the search field each time the popover opens.
    useEffect(() => {
        if (!open) return;
        setQuery("");
        const id = window.setTimeout(() => searchRef.current?.focus(), 0);
        return () => window.clearTimeout(id);
    }, [open]);

    const filtered = useMemo(() => {
        const q = query.trim().toLowerCase();
        if (!q) return FONT_CATALOG;
        return FONT_CATALOG.filter((f) => f.family.toLowerCase().includes(q));
    }, [query]);

    const grouped = useMemo(() => {
        const byCat = new Map();
        for (const f of filtered) {
            const list = byCat.get(f.category) ?? [];
            list.push(f);
            byCat.set(f.category, list);
        }
        return FONT_CATEGORIES.map((cat) => ({...cat, fonts: byCat.get(cat.id) ?? []})).filter(
            (cat) => cat.fonts.length > 0
        );
    }, [filtered]);

    const selectedEntry = useMemo(
        () => FONT_CATALOG.find((f) => f.family === selectedFamily) ?? null,
        [selectedFamily]
    );

    function pick(font) {
        onChange?.(font ? font.stack : "");
        setOpen(false);
    }

    const previewText = selectedFamily || __("messages.fonts.inherit");
    // For the trigger, render the selected font in its own typeface. For
    // unknown fonts (not in catalog), fall back to the raw value as-is so
    // slides saved elsewhere still show a meaningful label.
    const triggerFontFamily = selectedEntry?.stack ?? value ?? "";

    return (
        <Popover open={open} onOpenChange={setOpen}>
            <PopoverTrigger asChild>
                <button
                    type="button"
                    disabled={disabled}
                    aria-label={__("messages.inspector.font")}
                    className="input-base focus-ring flex h-9 w-full items-center justify-between gap-2 px-2 text-left disabled:opacity-50"
                >
                    <span className="flex min-w-0 items-center gap-2">
                        <Type className="size-3.5 shrink-0 text-[var(--muted-foreground)]" />
                        <span
                            className="truncate text-[13px]"
                            style={triggerFontFamily ? {fontFamily: triggerFontFamily} : undefined}
                        >
                            {previewText}
                        </span>
                    </span>
                    <span className="shrink-0 text-[10px] uppercase tracking-wider text-[var(--muted-foreground)]">
                        {selectedEntry ? __(selectedEntry.category ? `messages.fonts.category_${selectedEntry.category}` : "") : __("messages.fonts.inherit")}
                    </span>
                </button>
            </PopoverTrigger>
            <PopoverContent
                align="start"
                sideOffset={6}
                collisionPadding={12}
                className="flex w-[260px] max-h-[min(420px,var(--radix-popover-content-available-height))] flex-col overflow-hidden p-0"
                onOpenAutoFocus={(e) => e.preventDefault()}
            >
                <div className="flex shrink-0 items-center gap-2 border-b border-[var(--border)] px-2.5 py-2">
                    <Search className="size-3.5 shrink-0 text-[var(--muted-foreground)]" />
                    <input
                        ref={searchRef}
                        type="search"
                        value={query}
                        onChange={(e) => setQuery(e.target.value)}
                        placeholder={__("messages.fonts.search_placeholder")}
                        className="h-7 w-full bg-transparent text-[12.5px] outline-none placeholder:text-[var(--muted-foreground)]"
                        autoComplete="off"
                        spellCheck={false}
                    />
                </div>
                <div className="min-h-0 flex-1 overflow-y-auto overscroll-contain" data-font-list>
                    <div className="p-1.5">
                        <FontOption
                            active={selectedFamily === ""}
                            label={__("messages.fonts.inherit")}
                            stack=""
                            onClick={() => pick(null)}
                        />
                        {grouped.length === 0 && (
                            <div className="px-2 py-6 text-center text-[11.5px] text-[var(--muted-foreground)]">
                                {__("messages.fonts.no_results")}
                            </div>
                        )}
                        {grouped.map((cat) => (
                            <div key={cat.id} className="mt-1.5 first:mt-0">
                                <div className="px-2 py-1 text-[10px] font-bold uppercase tracking-[0.09em] text-[var(--muted-foreground)]">
                                    {__(cat.labelKey)}
                                </div>
                                {cat.fonts.map((font) => (
                                    <FontOption
                                        key={font.family}
                                        active={font.family === selectedFamily}
                                        label={font.family}
                                        stack={font.stack}
                                        onClick={() => pick(font)}
                                    />
                                ))}
                            </div>
                        ))}
                    </div>
                </div>
            </PopoverContent>
        </Popover>
    );
}

function FontOption({active, label, stack, onClick}) {
    return (
        <button
            type="button"
            onClick={onClick}
            className={cn(
                "flex w-full items-center justify-between gap-2 rounded-md px-2 py-1.5 text-left text-[13px] outline-none transition-colors",
                "hover:bg-[var(--navy)]/5 focus-visible:bg-[var(--navy)]/5",
                active && "bg-[var(--navy)]/10 text-[var(--navy)]"
            )}
            style={stack ? {fontFamily: stack} : undefined}
        >
            <span className="truncate">{label}</span>
            {active && <Check className="size-3.5 shrink-0" />}
        </button>
    );
}

export default FontSelector;
